//! trust-escape-ledger: enumerate every input-narrowing assumption in the
//! proof harnesses and compare the set against a committed baseline.
//!
//! The ledger may only shrink (SWREQ-REL-003, objective O3). The check fails
//! on growth (an entry not in the baseline) and on a stale baseline (an entry
//! no longer in the tree), so the baseline diff is always a reviewed change.
//!
//! Scanned escapes:
//! - `kani::assume(` in any `.rs` file under the scan roots
//! - Verus escape tokens (`assume(`, `admit(`, `external_body`, `axiom`)
//!   under `proofs/`
//! - explicit `trust-escape:` marker comments (for narrowings a token scan
//!   cannot see, e.g. proptest domains)
//!
//! Comment-only lines are skipped. Blind spots (stated in the emitted
//! north-star input): assumes generated by macros, multi-line comment bodies,
//! and assumptions living in dependencies.

use std::fmt::Write as _;
use std::fs;
use std::path::{Path, PathBuf};
use std::process::ExitCode;

const VERSION: &str = env!("CARGO_PKG_VERSION");
const SCAN_ROOTS: &[&str] = &["crates", "proofs"];
const DEFAULT_BASELINE: &str = "tools/trust-escape-ledger/baseline.tsv";

#[derive(Debug, Clone, PartialEq, Eq, PartialOrd, Ord)]
struct Entry {
    kind: String,
    file: String,
    /// nth occurrence (0-based) of this exact (kind, file, text) triple, so
    /// the id survives line moves but duplicates stay distinct.
    nth: u32,
    text: String,
}

fn is_comment_line(trimmed: &str) -> bool {
    trimmed.starts_with("//") || trimmed.starts_with('*') || trimmed.starts_with("/*")
}

fn scan_file(rel: &str, content: &str, out: &mut Vec<Entry>) {
    let in_proofs = rel.starts_with("proofs/");
    for line in content.lines() {
        let trimmed = line.trim();
        if is_comment_line(trimmed) {
            // A marker inside a comment is still a declared escape.
            if trimmed.contains("trust-escape:") {
                push(out, "marker", rel, trimmed);
            }
            continue;
        }
        if trimmed.contains("kani::assume(") {
            push(out, "kani-assume", rel, trimmed);
        } else if in_proofs
            && (trimmed.contains("assume(")
                || trimmed.contains("admit(")
                || trimmed.contains("external_body")
                || trimmed.contains("axiom"))
        {
            push(out, "verus-escape", rel, trimmed);
        }
        if trimmed.contains("trust-escape:") {
            push(out, "marker", rel, trimmed);
        }
    }
}

fn push(out: &mut Vec<Entry>, kind: &str, file: &str, text: &str) {
    let nth = out
        .iter()
        .filter(|e| e.kind == kind && e.file == file && e.text == text)
        .count() as u32;
    out.push(Entry {
        kind: kind.to_string(),
        file: file.to_string(),
        nth,
        text: text.to_string(),
    });
}

fn walk(root: &Path, base: &Path, files: &mut Vec<PathBuf>) -> Result<(), String> {
    let it = fs::read_dir(root).map_err(|e| format!("read_dir {}: {e}", root.display()))?;
    for ent in it {
        let ent = ent.map_err(|e| format!("read_dir entry under {}: {e}", root.display()))?;
        let p = ent.path();
        let name = ent.file_name();
        let name = name.to_string_lossy();
        if p.is_dir() {
            if name == "target" || name.starts_with('.') {
                continue;
            }
            walk(&p, base, files)?;
        } else if name.ends_with(".rs") {
            // The ledger tool's own sources mention the tokens it scans for.
            if p.strip_prefix(base)
                .map(|r| r.starts_with("tools/trust-escape-ledger"))
                .unwrap_or(false)
            {
                continue;
            }
            files.push(p);
        }
    }
    Ok(())
}

fn scan(repo: &Path) -> Result<Vec<Entry>, String> {
    let mut files = Vec::new();
    let mut roots_seen = 0usize;
    for root in SCAN_ROOTS {
        let r = repo.join(root);
        if r.is_dir() {
            roots_seen += 1;
            walk(&r, repo, &mut files)?;
        }
    }
    if roots_seen == 0 || files.is_empty() {
        // Fail closed: nothing scanned must never read as "no escapes".
        return Err(format!(
            "nothing scanned: no .rs files under {:?} relative to {}",
            SCAN_ROOTS,
            repo.display()
        ));
    }
    files.sort();
    let mut out = Vec::new();
    for f in &files {
        let content = fs::read_to_string(f).map_err(|e| format!("read {}: {e}", f.display()))?;
        let rel = f
            .strip_prefix(repo)
            .map_err(|_| format!("{} outside repo", f.display()))?
            .to_string_lossy()
            .replace('\\', "/");
        scan_file(&rel, &content, &mut out);
    }
    out.sort();
    Ok(out)
}

fn to_tsv(entries: &[Entry]) -> String {
    let mut s = String::new();
    for e in entries {
        let _ = writeln!(s, "{}\t{}\t{}\t{}", e.kind, e.file, e.nth, e.text);
    }
    s
}

fn from_tsv(s: &str) -> Result<Vec<Entry>, String> {
    let mut out = Vec::new();
    for (i, line) in s.lines().enumerate() {
        if line.trim().is_empty() {
            continue;
        }
        let mut parts = line.splitn(4, '\t');
        let (Some(kind), Some(file), Some(nth), Some(text)) =
            (parts.next(), parts.next(), parts.next(), parts.next())
        else {
            return Err(format!(
                "baseline line {}: expected 4 tab-separated fields",
                i + 1
            ));
        };
        let nth: u32 = nth
            .parse()
            .map_err(|_| format!("baseline line {}: bad occurrence index", i + 1))?;
        out.push(Entry {
            kind: kind.to_string(),
            file: file.to_string(),
            nth,
            text: text.to_string(),
        });
    }
    out.sort();
    Ok(out)
}

struct Diff {
    growth: Vec<Entry>,
    stale: Vec<Entry>,
}

fn diff(current: &[Entry], baseline: &[Entry]) -> Diff {
    Diff {
        growth: current
            .iter()
            .filter(|e| !baseline.contains(e))
            .cloned()
            .collect(),
        stale: baseline
            .iter()
            .filter(|e| !current.contains(e))
            .cloned()
            .collect(),
    }
}

fn json_escape(s: &str) -> String {
    let mut out = String::with_capacity(s.len() + 2);
    for c in s.chars() {
        match c {
            '"' => out.push_str("\\\""),
            '\\' => out.push_str("\\\\"),
            '\n' => out.push_str("\\n"),
            '\t' => out.push_str("\\t"),
            c if (c as u32) < 0x20 => {
                let _ = write!(out, "\\u{:04x}", c as u32);
            }
            c => out.push(c),
        }
    }
    out
}

fn report_json(current: &[Entry], d: &Diff, pass: bool) -> String {
    let ent = |list: &[Entry]| -> String {
        let items: Vec<String> = list
            .iter()
            .map(|e| {
                format!(
                    "{{\"kind\":\"{}\",\"file\":\"{}\",\"nth\":{},\"text\":\"{}\"}}",
                    json_escape(&e.kind),
                    json_escape(&e.file),
                    e.nth,
                    json_escape(&e.text)
                )
            })
            .collect();
        format!("[{}]", items.join(","))
    };
    format!(
        "{{\"schema\":\"trust-escape-ledger.v1\",\"pass\":{},\"count\":{},\"entries\":{},\"growth\":{},\"stale\":{}}}\n",
        pass,
        current.len(),
        ent(current),
        ent(&d.growth),
        ent(&d.stale)
    )
}

fn north_star_input(
    repo_slug: &str,
    version: &str,
    generated_at: &str,
    count: usize,
    pass: bool,
    control: Option<bool>,
    evidence: Option<&str>,
) -> String {
    let mut fact = format!(
        "{{\"id\":\"ledger\",\"ran\":true,\"pass\":{pass},\"detail\":{{\"entries\":{count},\"baseline\":\"{}\"}}",
        json_escape(DEFAULT_BASELINE)
    );
    if let Some(c) = control {
        let _ = write!(fact, ",\"control_failed_as_expected\":{c}");
    }
    if let Some(ev) = evidence {
        let _ = write!(fact, ",\"evidence\":\"{}\"", json_escape(ev));
    }
    fact.push('}');
    format!(
        "{{\n  \"schema_version\": 1,\n  \"objective\": \"O3\",\n  \"repo\": \"{}\",\n  \"version\": \"{}\",\n  \"generated_at\": \"{}\",\n  \"generator\": {{\"tool\": \"trust-escape-ledger\", \"version\": \"{}\"}},\n  \"facts\": [{}],\n  \"not_measured\": [\n    \"assumes generated by macro expansion\",\n    \"escape tokens spread over multiple lines or inside multi-line comments\",\n    \"assumptions inside dependency crates\",\n    \"proptest domain narrowings without a trust-escape: marker\"\n  ]\n}}\n",
        json_escape(repo_slug),
        json_escape(version),
        json_escape(generated_at),
        VERSION,
        fact
    )
}

fn usage() -> String {
    format!(
        "trust-escape-ledger {VERSION}\n\
         Enumerate proof-harness input-narrowing assumptions; the ledger may only shrink.\n\n\
         USAGE:\n  trust-escape-ledger [OPTIONS]\n\n\
         OPTIONS:\n\
         \x20 --repo <DIR>             repository root to scan (default: .)\n\
         \x20 --baseline <FILE>        baseline file (default: {DEFAULT_BASELINE})\n\
         \x20 --write                  rewrite the baseline from the current scan\n\
         \x20 --format json            machine-readable report on stdout\n\
         \x20 --emit-input <FILE>      write north-star-input.O3.json (schema_version 1)\n\
         \x20 --release-version <VER>  version recorded in the emitted input (required with --emit-input)\n\
         \x20 --control-result <BOOL>  planted negative control outcome, recorded in the emitted input\n\
         \x20 --evidence <URL>         evidence URL recorded in the emitted input\n\
         \x20 -V, --version            print version\n\
         \x20 -h, --help               print this help\n"
    )
}

fn run() -> Result<ExitCode, String> {
    let mut repo = PathBuf::from(".");
    let mut baseline_path: Option<PathBuf> = None;
    let mut write = false;
    let mut format_json = false;
    let mut emit_input: Option<PathBuf> = None;
    let mut release_version: Option<String> = None;
    let mut control: Option<bool> = None;
    let mut evidence: Option<String> = None;

    let mut args = std::env::args().skip(1);
    while let Some(a) = args.next() {
        let mut want = |name: &str| -> Result<String, String> {
            args.next().ok_or(format!("{name} needs a value"))
        };
        match a.as_str() {
            "--repo" => repo = PathBuf::from(want("--repo")?),
            "--baseline" => baseline_path = Some(PathBuf::from(want("--baseline")?)),
            "--write" => write = true,
            "--format" => {
                let v = want("--format")?;
                if v != "json" {
                    return Err(format!("unknown format {v:?}; only json"));
                }
                format_json = true;
            }
            "--emit-input" => emit_input = Some(PathBuf::from(want("--emit-input")?)),
            "--release-version" => release_version = Some(want("--release-version")?),
            "--control-result" => {
                control = Some(match want("--control-result")?.as_str() {
                    "true" => true,
                    "false" => false,
                    v => return Err(format!("--control-result takes true|false, not {v:?}")),
                })
            }
            "--evidence" => evidence = Some(want("--evidence")?),
            "-V" | "--version" => {
                println!("trust-escape-ledger {VERSION}");
                return Ok(ExitCode::SUCCESS);
            }
            "-h" | "--help" => {
                print!("{}", usage());
                return Ok(ExitCode::SUCCESS);
            }
            other => {
                eprintln!("unknown option {other:?}\n\n{}", usage());
                return Ok(ExitCode::from(2));
            }
        }
    }

    let baseline_path = baseline_path.unwrap_or_else(|| repo.join(DEFAULT_BASELINE));
    let current = scan(&repo)?;

    if write {
        fs::write(&baseline_path, to_tsv(&current))
            .map_err(|e| format!("write {}: {e}", baseline_path.display()))?;
        eprintln!(
            "baseline rewritten: {} entries -> {}",
            current.len(),
            baseline_path.display()
        );
        return Ok(ExitCode::SUCCESS);
    }

    let baseline_raw = fs::read_to_string(&baseline_path).map_err(|e| {
        format!(
            "read baseline {}: {e} (run with --write to create it)",
            baseline_path.display()
        )
    })?;
    let baseline = from_tsv(&baseline_raw)?;
    let d = diff(&current, &baseline);
    let pass = d.growth.is_empty() && d.stale.is_empty();

    if format_json {
        print!("{}", report_json(&current, &d, pass));
    } else {
        for e in &d.growth {
            println!("GROWTH  {}  ({})  {}", e.file, e.kind, e.text);
        }
        for e in &d.stale {
            println!("STALE   {}  ({})  {}", e.file, e.kind, e.text);
        }
        println!(
            "trust-escape ledger: {} entries, {} growth, {} stale -> {}",
            current.len(),
            d.growth.len(),
            d.stale.len(),
            if pass { "PASS" } else { "FAIL" }
        );
    }

    if let Some(out) = emit_input {
        let version = release_version.ok_or("--emit-input requires --release-version")?;
        let now = unix_now_iso8601();
        let body = north_star_input(
            "pulseengine/wohl",
            &version,
            &now,
            current.len(),
            pass,
            control,
            evidence.as_deref(),
        );
        fs::write(&out, body).map_err(|e| format!("write {}: {e}", out.display()))?;
        eprintln!("north-star input written: {}", out.display());
    }

    Ok(if pass {
        ExitCode::SUCCESS
    } else {
        ExitCode::FAILURE
    })
}

/// UTC now as RFC 3339, from the Unix clock alone (no chrono dependency).
fn unix_now_iso8601() -> String {
    let secs = std::time::SystemTime::now()
        .duration_since(std::time::UNIX_EPOCH)
        .map(|d| d.as_secs())
        .unwrap_or(0);
    iso8601_from_unix(secs)
}

fn iso8601_from_unix(secs: u64) -> String {
    let days = secs / 86400;
    let (h, m, s) = ((secs % 86400) / 3600, (secs % 3600) / 60, secs % 60);
    // Civil-from-days (Howard Hinnant's algorithm), valid for the Unix era.
    let z = days as i64 + 719_468;
    let era = z.div_euclid(146_097);
    let doe = z.rem_euclid(146_097);
    let yoe = (doe - doe / 1460 + doe / 36524 - doe / 146_096) / 365;
    let y = yoe + era * 400;
    let doy = doe - (365 * yoe + yoe / 4 - yoe / 100);
    let mp = (5 * doy + 2) / 153;
    let d = doy - (153 * mp + 2) / 5 + 1;
    let mth = if mp < 10 { mp + 3 } else { mp - 9 };
    let y = if mth <= 2 { y + 1 } else { y };
    format!("{y:04}-{mth:02}-{d:02}T{h:02}:{m:02}:{s:02}Z")
}

fn main() -> ExitCode {
    match run() {
        Ok(code) => code,
        Err(e) => {
            eprintln!("trust-escape-ledger: {e}");
            ExitCode::FAILURE
        }
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    // rivet: verifies SWREQ-REL-003
    #[test]
    fn detects_kani_assume_and_skips_comments() {
        let mut out = Vec::new();
        let src = "// kani::assume(x) in a comment\nkani::assume(v > 0);\n";
        scan_file("crates/x/plain/src/engine.rs", src, &mut out);
        assert_eq!(out.len(), 1);
        assert_eq!(out[0].kind, "kani-assume");
        assert_eq!(out[0].text, "kani::assume(v > 0);");
    }

    // rivet: verifies SWREQ-REL-003
    #[test]
    fn duplicate_lines_stay_distinct() {
        let mut out = Vec::new();
        let src = "kani::assume(a);\nkani::assume(a);\n";
        scan_file("f.rs", src, &mut out);
        assert_eq!(out.len(), 2);
        assert_eq!((out[0].nth, out[1].nth), (0, 1));
    }

    // rivet: verifies SWREQ-REL-003
    #[test]
    fn verus_tokens_only_under_proofs() {
        let mut out = Vec::new();
        scan_file("proofs/verus/p.rs", "admit();\n", &mut out);
        scan_file("crates/x/src/lib.rs", "admit();\n", &mut out);
        assert_eq!(out.len(), 1);
        assert_eq!(out[0].kind, "verus-escape");
    }

    // rivet: verifies SWREQ-REL-003
    #[test]
    fn marker_counts_even_in_comments() {
        let mut out = Vec::new();
        scan_file(
            "f.rs",
            "// trust-escape: proptest domain is 0..100\n",
            &mut out,
        );
        assert_eq!(out.len(), 1);
        assert_eq!(out[0].kind, "marker");
    }

    // rivet: verifies SWREQ-REL-003
    #[test]
    fn growth_and_stale_both_fail() {
        let base = from_tsv("kani-assume\tf.rs\t0\tkani::assume(a);\n").unwrap();
        let mut cur = Vec::new();
        scan_file("f.rs", "kani::assume(b);\n", &mut cur);
        let d = diff(&cur, &base);
        assert_eq!(d.growth.len(), 1);
        assert_eq!(d.stale.len(), 1);
    }

    // rivet: verifies SWREQ-REL-003
    #[test]
    fn tsv_roundtrip() {
        let mut cur = Vec::new();
        scan_file("a.rs", "kani::assume(x);\nkani::assume(x);\n", &mut cur);
        let back = from_tsv(&to_tsv(&cur)).unwrap();
        assert_eq!(cur, back);
    }

    #[test]
    fn emitted_input_matches_schema_shape() {
        let s = north_star_input(
            "pulseengine/wohl",
            "v0.8.0",
            "2026-11-20T00:00:00Z",
            14,
            true,
            Some(true),
            None,
        );
        for key in [
            "\"schema_version\": 1",
            "\"objective\": \"O3\"",
            "\"facts\"",
            "\"ran\":true",
            "\"not_measured\"",
            "\"control_failed_as_expected\":true",
        ] {
            assert!(s.contains(key), "missing {key} in {s}");
        }
    }

    #[test]
    fn date_math_is_sane() {
        assert_eq!(iso8601_from_unix(0), "1970-01-01T00:00:00Z");
        assert_eq!(iso8601_from_unix(1_795_132_800), "2026-11-20T00:00:00Z");
        assert_eq!(iso8601_from_unix(1_740_787_199), "2025-02-28T23:59:59Z");
    }
}
